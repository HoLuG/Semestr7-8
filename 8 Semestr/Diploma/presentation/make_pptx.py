prs = Presentation()
prs.slide_width  = W
prs.slide_height = H

def blank_slide(prs):
    blank_layout = prs.slide_layouts[6]   # completely blank
    return prs.slides.add_slide(blank_layout)

def rect(slide, left, top, width, height, fill_rgb):
    from pptx.util import Emu
    shape = slide.shapes.add_shape(
        1,  # MSO_SHAPE_TYPE.RECTANGLE = 1  →  actually use freeform? No, use add_shape
        left, top, width, height
    )
    shape.line.fill.background()   # no border
    shape.fill.solid()
    shape.fill.fore_color.rgb = fill_rgb
    return shape

def add_text_box(slide, text, left, top, width, height,
                 font_size=18, bold=False, color=BLACK,
                 align=PP_ALIGN.LEFT, word_wrap=True):
    tb = slide.shapes.add_textbox(left, top, width, height)
    tf = tb.text_frame
    tf.word_wrap = word_wrap
    p = tf.paragraphs[0]
    p.alignment = align
    run = p.add_run()
    run.text = text
    run.font.size = Pt(font_size)
    run.font.bold = bold
    run.font.color.rgb = color
    return tb

def add_slide_number(slide, number):
    add_text_box(slide, str(number),
                 W - Inches(0.7), H - Inches(0.45),
                 Inches(0.5), Inches(0.35),
                 font_size=14, color=GRAY, align=PP_ALIGN.RIGHT)

def add_header_bar(slide, title_text):
    """Blue bar at top with slide title."""
    bar = rect(slide, 0, 0, W, Inches(1.1), MID_BLUE)
    add_text_box(slide, title_text,
                 Inches(0.35), Inches(0.15),
                 W - Inches(0.7), Inches(0.85),
                 font_size=28, bold=True, color=WHITE, align=PP_ALIGN.LEFT)

def content_slide(prs, number, title, bullets):
    """Standard content slide: blue header + bullet list."""
    slide = blank_slide(prs)
    # bg
    rect(slide, 0, 0, W, H, LIGHT_BLUE)
    # header
    add_header_bar(slide, title)
    # bullet area
    tb = slide.shapes.add_textbox(Inches(0.5), Inches(1.25),
                                   W - Inches(1.0), H - Inches(1.85))
    tf = tb.text_frame
    tf.word_wrap = True
    first = True
    for line in bullets:
        if first:
            p = tf.paragraphs[0]
            first = False
        else:
            p = tf.add_paragraph()
        p.space_before = Pt(2)
        p.space_after  = Pt(2)
        indent = 0
        text = line
        if line.startswith("    "):          # 4 spaces → level-2
            indent = 1
            text = line.lstrip()
        run = p.add_run()
        run.text = text
        run.font.size = Pt(20)
        run.font.color.rgb = BLACK if indent == 0 else GRAY
        p.level = indent
    add_slide_number(slide, number)
    return slide

